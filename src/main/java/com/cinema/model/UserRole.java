package com.cinema.model;

/** Перечисление ролей пользователей в системе кинотеатра. */
public enum UserRole {
    /** Администратор с полным доступом к управлению системой и пользователями. */
    ADMIN,
    /** Менеджер, отвечающий за управление залами, фильмами и сеансами. */
    MANAGER,
    /** Покупатель, который просматривает расписание и покупает билеты. */
    CUSTOMER
}